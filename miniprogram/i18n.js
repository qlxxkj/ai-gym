function sysLang() {
  try {
    return (wx.getSystemInfoSync().language || "zh").indexOf("en") === 0 ? "en" : "zh";
  } catch (e) {
    return "zh";
  }
}

function get() {
  const v = wx.getStorageSync("lang") || "auto";
  return v === "auto" ? sysLang() : v;
}

function set(v) {
  wx.setStorageSync("lang", v || "auto");
}

function bundle() {
  return get() === "en" ? EN : ZH;
}

module.exports = { get, set, bundle, isEn: () => get() === "en" };
